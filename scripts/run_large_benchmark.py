import subprocess
import os
import glob

# Determine project root (one level up from this script's directory)
ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
PYTHON_EXE = os.path.join(ROOT_DIR, 'venv', 'Scripts', 'python.exe')

# Directory where experiment results are stored
RESULTS_DIR = os.path.join(ROOT_DIR, 'experiments', 'results', 'run_all_experiments')

def has_existing_results():
    """Check if any JSON result files already exist in the results directory."""
    if not os.path.isdir(RESULTS_DIR):
        return False
    # Look for any .json files generated by the experiments
    return any(glob.glob(os.path.join(RESULTS_DIR, '*.json')))

def run_script(rel_path):
    script_path = os.path.abspath(os.path.join(ROOT_DIR, rel_path))
    print(f"Running {script_path} ...")
    subprocess.check_call([PYTHON_EXE, script_path], cwd=ROOT_DIR)

if __name__ == "__main__":
    # If results already exist, skip re-running the heavy experiments
    if has_existing_results():
        print("Result files detected – skipping experiment execution.")
    else:
        # Run the full suite of experiments (including large‑scale ones)
        run_script('experiments/python/run_all_experiments.py')
    # Always generate the publication‑quality plots
    run_script('experiments/python/generate_plots.py')
    print("Benchmark and plot generation completed.")
